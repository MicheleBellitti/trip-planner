#!/usr/bin/env python3
"""Render the per-profile agent files from the single-source templates in agents/.

From backend/ (uses the backend venv for PyYAML):

    uv run python ../scripts/render_profiles.py           # write every generated file
    uv run python ../scripts/render_profiles.py --check   # exit 1 if a file is stale or unexpected

Inputs (hand-written):

    agents/profiles.yaml             models and numbers per profile
    agents/<name>.md                 coordinator, flights, lodging, activities, transport
    agents/environment.yaml          the Managed Agents environment
    schema/plan.json                 generated by `python -m app.schemas` (backend)
    schema/ask_traveller.json        generated by `python -m app.schemas` (backend)
    schema/results/<agent>.json      generated by `python -m app.schemas` (backend)

Outputs (generated, never edited by hand):

    profiles/<profile>/agents/<name>.md               one per agent, the format `ant apply` reads
    profiles/<profile>/agents/tools/submit_plan.json  coordinator's custom tool, every $ref inlined
    profiles/<profile>/agents/tools/ask_traveller.json  coordinator's second custom tool, same
    profiles/<profile>/environments/cloud.yaml        the environment
    skills/travel-research-rules/schemas/<agent>.json copies of schema/results/<agent>.json

Templates use `{{ key }}` placeholders (keys listed in agents/profiles.yaml). Lines starting
with `#!` in a template's YAML are template notes and are dropped; other comments are kept.
Rendering is deterministic, so `--check` can run in CI. In write mode, a file under a generated
directory that no template produces is deleted (a removed agent must not linger and be applied).
"""

from __future__ import annotations

import argparse
import copy
import json
import re
import sys
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]

AGENTS: tuple[str, ...] = ("coordinator", "flights", "lodging", "activities", "transport")
SUBAGENTS: tuple[str, ...] = AGENTS[1:]
PROFILE_NAMES: tuple[str, ...] = ("development", "production")

TEMPLATES_DIR = Path("agents")
PROFILES_FILE = TEMPLATES_DIR / "profiles.yaml"
ENVIRONMENT_TEMPLATE = TEMPLATES_DIR / "environment.yaml"
PROFILES_DIR = Path("profiles")
RESULT_SCHEMAS_DIR = Path("schema/results")
SKILL_SCHEMAS_DIR = Path("skills/travel-research-rules/schemas")

AGENT_DIR = "agents"
ENVIRONMENT_FILE = "environments/cloud.yaml"

GENERATED_DIRS: tuple[Path, ...] = (PROFILES_DIR, SKILL_SCHEMAS_DIR)
"""Directories that hold only generated files: anything else found there is unexpected."""

SUBMIT_PLAN_DESCRIPTION = (
    "Submit the trip plan. Call it once the research is complete and the plan passes your "
    "coherence check. The backend validates the plan and translates it for TripTracker: the "
    "answer is 'Plan accepted.' or the list of validation errors. Fix every listed error and "
    "call it again; three rejected submissions fail the plan."
)
ASK_TRAVELLER_DESCRIPTION = (
    "Ask the traveller to choose among 2 to 6 options, shown as cards with photos, only at the "
    "moments your instructions name. The call returns when the traveller answers, or after a few "
    "minutes without an answer: the result names the picked option ids, or says the traveller "
    "let you choose. An error result means nothing was shown; your instructions say what each "
    "one asks of you."
)


@dataclass(frozen=True)
class CustomTool:
    """A coordinator custom tool: its input schema (generated by the backend) becomes a file."""

    name: str
    schema: Path
    file: str
    description: str


CUSTOM_TOOLS: tuple[CustomTool, ...] = (
    CustomTool(
        "submit_plan",
        Path("schema/plan.json"),
        "agents/tools/submit_plan.json",
        SUBMIT_PLAN_DESCRIPTION,
    ),
    CustomTool(
        "ask_traveller",
        Path("schema/ask_traveller.json"),
        "agents/tools/ask_traveller.json",
        ASK_TRAVELLER_DESCRIPTION,
    ),
)

AGENT_FIELDS = frozenset(
    {
        "name",
        "description",
        "model",
        "system",
        "tools",
        "mcp_servers",
        "skills",
        "multiagent",
        "metadata",
    }
)
"""Top-level fields of POST /v1/agents that a template may set (`system` comes from the body)."""

PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z0-9_.]+)\s*\}\}")
LOCAL_REF_PREFIX = "#/$defs/"
FENCE = "---"


class RenderError(Exception):
    """A template, a profile value or an input schema is wrong; the message says which file."""


@dataclass
class Rendered:
    """Every generated file (path relative to the repository root -> bytes), plus warnings
    about references the renderer could not check (a skill directory not written yet)."""

    files: dict[Path, bytes] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)


# --- profiles -----------------------------------------------------------------------------------

PROFILE_KEYS = frozenset(
    {
        "environment_name",
        "models",
        "efforts",
        "session_budget_cents",
        "web_search_cap",
        "web_fetch_cap",
        "web_fetch_max_content_tokens",
        "max_follow_ups",
    }
)
EFFORT_LEVELS = frozenset({"low", "medium", "high", "xhigh", "max"})
"""Effort levels of the agent's `model` object (SDK BetaManagedAgentsModelConfigParams.effort)."""


def load_profiles(repo_root: Path) -> dict[str, dict[str, Any]]:
    """agents/profiles.yaml, validated: both profiles, every key, every agent's model."""
    path = repo_root / PROFILES_FILE
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise RenderError(f"{PROFILES_FILE}: {exc}") from exc
    profiles = data.get("profiles") if isinstance(data, dict) else None
    if not isinstance(profiles, dict) or set(profiles) != set(PROFILE_NAMES):
        raise RenderError(
            f"{PROFILES_FILE}: `profiles` must define exactly {', '.join(PROFILE_NAMES)}"
        )
    for name, values in profiles.items():
        where = f"{PROFILES_FILE}: profiles.{name}"
        if not isinstance(values, dict) or set(values) != PROFILE_KEYS:
            raise RenderError(
                f"{where} must have exactly the keys {', '.join(sorted(PROFILE_KEYS))}"
            )
        models = values["models"]
        if not isinstance(models, dict) or set(models) != set(AGENTS):
            raise RenderError(f"{where}.models must name a model for each of {', '.join(AGENTS)}")
        for agent, model in models.items():
            if not isinstance(model, str) or not re.fullmatch(r"claude-[a-z0-9-]+", model):
                raise RenderError(f"{where}.models.{agent} is not a model id: {model!r}")
        efforts = values["efforts"]
        if not isinstance(efforts, dict) or set(efforts) != set(AGENTS):
            raise RenderError(
                f"{where}.efforts must name an effort for each of {', '.join(AGENTS)}"
            )
        for agent, effort in efforts.items():
            if effort not in EFFORT_LEVELS:
                raise RenderError(
                    f"{where}.efforts.{agent} must be one of {', '.join(sorted(EFFORT_LEVELS))}: "
                    f"{effort!r}"
                )
        for key in (
            "session_budget_cents",
            "web_search_cap",
            "web_fetch_cap",
            "web_fetch_max_content_tokens",
            "max_follow_ups",
        ):
            if not isinstance(values[key], int) or isinstance(values[key], bool) or values[key] < 1:
                raise RenderError(f"{where}.{key} must be a positive integer")
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,62}", str(values["environment_name"])):
            raise RenderError(f"{where}.environment_name must be a short lowercase slug")
    return profiles


def template_context(profile: str, values: Mapping[str, Any]) -> dict[str, str]:
    """The flat `{{ key }}` namespace of one profile."""
    cents = int(values["session_budget_cents"])
    context = {
        "profile": profile,
        "environment_name": str(values["environment_name"]),
        "session_budget_cents": str(cents),
        "session_budget_usd": f"{cents // 100}.{cents % 100:02d}",
        "web_search_cap": str(values["web_search_cap"]),
        "web_fetch_cap": str(values["web_fetch_cap"]),
        "web_fetch_max_content_tokens": str(values["web_fetch_max_content_tokens"]),
        "max_follow_ups": str(values["max_follow_ups"]),
    }
    for agent, model in values["models"].items():
        context[f"models.{agent}"] = str(model)
    for agent, effort in values["efforts"].items():
        context[f"efforts.{agent}"] = str(effort)
    return context


# --- templates ----------------------------------------------------------------------------------


def substitute(text: str, context: Mapping[str, str], *, source: str) -> str:
    """Replace every `{{ key }}`; an unknown key or a leftover `{{` is an error."""

    def replace(match: re.Match[str]) -> str:
        key = match.group(1)
        if key not in context:
            raise RenderError(f"{source}: unknown placeholder {{{{ {key} }}}}")
        return context[key]

    out = PLACEHOLDER.sub(replace, text)
    if "{{" in out:
        raise RenderError(f"{source}: malformed placeholder near {out[out.index('{{') :][:40]!r}")
    return out


def drop_template_notes(yaml_text: str) -> str:
    """Remove the `#!` lines (notes about the template itself)."""
    return "".join(
        line for line in yaml_text.splitlines(keepends=True) if not line.lstrip().startswith("#!")
    )


def split_frontmatter(text: str, *, source: str) -> tuple[str, str]:
    """(frontmatter YAML, Markdown body) as `ant apply` splits them: an opening line of exactly
    `---` and the next line that is `---` close the frontmatter."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != FENCE:
        raise RenderError(f"{source}: must start with a `---` frontmatter fence")
    for index in range(1, len(lines)):
        if lines[index].strip() == FENCE:
            return "".join(lines[1:index]), "".join(lines[index + 1 :])
    raise RenderError(f"{source}: frontmatter is never closed with `---`")


def generated_header(sources: str, profile: str) -> str:
    return (
        f"# Generated by scripts/render_profiles.py from {sources} (profile: {profile}).\n"
        "# Do not edit: change the template, then re-render.\n"
    )


def render_agent(repo_root: Path, agent: str, profile: str, context: Mapping[str, str]) -> str:
    template_path = TEMPLATES_DIR / f"{agent}.md"
    try:
        text = (repo_root / template_path).read_text(encoding="utf-8")
    except OSError as exc:
        raise RenderError(f"{template_path}: {exc}") from exc
    front, body = split_frontmatter(text, source=str(template_path))
    front = substitute(drop_template_notes(front), context, source=str(template_path))
    body = substitute(body, context, source=str(template_path))
    header = generated_header(f"{template_path} and {PROFILES_FILE}", profile)
    return f"{FENCE}\n{header}{front}{FENCE}\n{body}"


def render_environment(repo_root: Path, profile: str, context: Mapping[str, str]) -> str:
    try:
        text = (repo_root / ENVIRONMENT_TEMPLATE).read_text(encoding="utf-8")
    except OSError as exc:
        raise RenderError(f"{ENVIRONMENT_TEMPLATE}: {exc}") from exc
    text = substitute(drop_template_notes(text), context, source=str(ENVIRONMENT_TEMPLATE))
    return generated_header(f"{ENVIRONMENT_TEMPLATE} and {PROFILES_FILE}", profile) + text


# --- custom tools -------------------------------------------------------------------------------


def inline_refs(schema: Mapping[str, Any], *, source: str = "plan.json") -> dict[str, Any]:
    """Resolve every local `#/$defs/...` reference in place and drop `$defs`.

    Keys written next to a `$ref` (a field's own `description`) override the referenced
    definition's. A non-local or dangling reference, or a recursive definition, is an error:
    the tool input_schema must be one self-contained object with no `$ref` at all.
    """
    definitions = schema.get("$defs", {})
    if not isinstance(definitions, dict):
        raise RenderError(f"{source}: `$defs` must be an object")

    def resolve(node: Any, stack: tuple[str, ...]) -> Any:
        if isinstance(node, list):
            return [resolve(item, stack) for item in node]
        if not isinstance(node, dict):
            return node
        if "$ref" in node:
            ref = node["$ref"]
            if not isinstance(ref, str) or not ref.startswith(LOCAL_REF_PREFIX):
                raise RenderError(f"{source}: non-local $ref {ref!r}")
            name = ref.removeprefix(LOCAL_REF_PREFIX)
            if name not in definitions:
                raise RenderError(f"{source}: $ref {ref!r} has no matching entry in $defs")
            if name in stack:
                raise RenderError(f"{source}: recursive definition {' -> '.join((*stack, name))}")
            target = resolve(definitions[name], (*stack, name))
            siblings = {key: resolve(value, stack) for key, value in node.items() if key != "$ref"}
            return {**target, **siblings}
        return {key: resolve(value, stack) for key, value in node.items() if key != "$defs"}

    inlined = resolve(copy.deepcopy(dict(schema)), ())
    if not isinstance(inlined, dict) or inlined.get("type") != "object":
        raise RenderError(f"{source}: a tool input_schema must describe an object")
    leftover = [key for key in iter_keys(inlined) if key in ("$ref", "$defs", "definitions")]
    if leftover:
        raise RenderError(f"{source}: references left after inlining: {sorted(set(leftover))}")
    return inlined


def iter_keys(node: Any):
    """Every dict key in a JSON value, depth first."""
    if isinstance(node, dict):
        for key, value in node.items():
            yield key
            yield from iter_keys(value)
    elif isinstance(node, list):
        for item in node:
            yield from iter_keys(item)


def render_custom_tool(repo_root: Path, tool: CustomTool) -> str:
    try:
        schema = json.loads((repo_root / tool.schema).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RenderError(f"{tool.schema}: {exc}") from exc
    body = {
        "type": "custom",
        "name": tool.name,
        "description": tool.description,
        "input_schema": inline_refs(schema, source=tool.schema.name),
    }
    return json.dumps(body, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# --- validation ---------------------------------------------------------------------------------


def parse_agent_file(text: str, *, source: str) -> tuple[dict[str, Any], str]:
    """(frontmatter fields, system prompt) of a rendered agent file."""
    front, body = split_frontmatter(text, source=source)
    try:
        fields = yaml.safe_load(front)
    except yaml.YAMLError as exc:
        raise RenderError(f"{source}: frontmatter is not valid YAML: {exc}") from exc
    if not isinstance(fields, dict):
        raise RenderError(f"{source}: frontmatter must be a mapping")
    return fields, body.strip()


def tools_of(fields: Mapping[str, Any]):
    """Every per-tool config entry of the agent toolset."""
    for tool in fields.get("tools") or []:
        if isinstance(tool, dict) and tool.get("type") == "agent_toolset_20260401":
            yield from (c for c in tool.get("configs") or [] if isinstance(c, dict))


def validate_agent(
    rel_path: Path, text: str, outputs: Mapping[Path, bytes], repo_root: Path, warnings: list[str]
) -> None:
    """Catch what the API would reject, or `ant apply` would resolve wrongly, before a deploy."""
    source = str(rel_path)
    fields, system = parse_agent_file(text, source=source)
    unknown = set(fields) - AGENT_FIELDS
    if unknown:
        raise RenderError(f"{source}: fields not accepted by POST /v1/agents: {sorted(unknown)}")
    if fields.get("name") != rel_path.stem:
        raise RenderError(f"{source}: `name` must be {rel_path.stem!r} (the backend's lane name)")
    model = fields.get("model")
    if not (
        isinstance(model, dict)
        and isinstance(model.get("id"), str)
        and model.get("effort") in EFFORT_LEVELS
        and set(model) <= {"id", "effort", "speed", "inference_geo"}
    ):
        raise RenderError(f"{source}: `model` must be {{id: <model id>, effort: <level>}}")
    for entry in tools_of(fields):
        if entry.get("name") == "web_fetch" and entry.get("enabled"):
            tokens = entry.get("max_content_tokens")
            if not isinstance(tokens, int) or isinstance(tokens, bool) or tokens < 1:
                raise RenderError(f"{source}: web_fetch needs a positive `max_content_tokens`")
    if not system:
        raise RenderError(f"{source}: the Markdown body (the system prompt) is empty")
    if "system" in fields:
        raise RenderError(f"{source}: `system` comes from the Markdown body, not the frontmatter")
    base = rel_path.parent

    tools = fields.get("tools") or []
    toolset_servers = set()
    for entry in tools:
        if isinstance(entry, str):
            if normalize(base / entry) not in outputs:
                raise RenderError(f"{source}: tool include {entry!r} is not a generated file")
        elif isinstance(entry, dict) and entry.get("type") == "mcp_toolset":
            toolset_servers.add(entry.get("mcp_server_name"))
    servers = {server.get("name") for server in fields.get("mcp_servers") or []}
    if servers != toolset_servers:
        raise RenderError(
            f"{source}: every MCP server needs exactly one mcp_toolset (servers {sorted(servers)}, "
            f"toolsets {sorted(toolset_servers)})"
        )

    multiagent = fields.get("multiagent") or {}
    predefined = (multiagent.get("subagents") or {}).get("predefined_agents") or []
    for entry in predefined:
        if not isinstance(entry, str) or normalize(base / entry) not in outputs:
            raise RenderError(f"{source}: predefined agent {entry!r} is not a generated agent")

    for entry in fields.get("skills") or []:
        if not isinstance(entry, str):
            continue
        skill_dir = normalize(base / entry)
        if not (repo_root / skill_dir / "SKILL.md").is_file():
            message = f"skill {skill_dir} has no SKILL.md yet (referenced by the agent files)"
            if message not in warnings:
                warnings.append(message)


def validate_environment(rel_path: Path, text: str) -> None:
    try:
        fields = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise RenderError(f"{rel_path}: not valid YAML: {exc}") from exc
    if not isinstance(fields, dict) or not isinstance(fields.get("name"), str):
        raise RenderError(f"{rel_path}: an environment needs a `name`")
    config = fields.get("config") or {}
    if config.get("type") != "cloud" or not isinstance(config.get("networking"), dict):
        raise RenderError(f"{rel_path}: `config` must be a cloud config with explicit networking")


def normalize(path: Path) -> Path:
    """Collapse `..` segments lexically (the targets may not exist yet)."""
    parts: list[str] = []
    for part in path.parts:
        if part == "..":
            if not parts:
                raise RenderError(f"{path} leaves the repository")
            parts.pop()
        elif part != ".":
            parts.append(part)
    return Path(*parts)


# --- whole set ----------------------------------------------------------------------------------


def build_outputs(repo_root: Path = REPO_ROOT) -> Rendered:
    """Every generated file's expected content, keyed by path relative to the repository."""
    rendered = Rendered()
    profiles = load_profiles(repo_root)
    tool_texts = {
        tool.file: render_custom_tool(repo_root, tool).encode("utf-8") for tool in CUSTOM_TOOLS
    }
    agent_texts: dict[Path, str] = {}

    for profile in PROFILE_NAMES:
        context = template_context(profile, profiles[profile])
        root = PROFILES_DIR / profile
        for tool_file, tool_text in tool_texts.items():
            rendered.files[root / tool_file] = tool_text
        environment = render_environment(repo_root, profile, context)
        validate_environment(root / ENVIRONMENT_FILE, environment)
        rendered.files[root / ENVIRONMENT_FILE] = environment.encode("utf-8")
        for agent in AGENTS:
            path = root / AGENT_DIR / f"{agent}.md"
            agent_texts[path] = render_agent(repo_root, agent, profile, context)
            rendered.files[path] = agent_texts[path].encode("utf-8")

    for path, text in agent_texts.items():
        validate_agent(path, text, rendered.files, repo_root, rendered.warnings)

    schemas = sorted((repo_root / RESULT_SCHEMAS_DIR).glob("*.json"))
    if {p.stem for p in schemas} != set(SUBAGENTS):
        raise RenderError(f"{RESULT_SCHEMAS_DIR}: expected one schema per subagent {SUBAGENTS}")
    for schema in schemas:
        rendered.files[SKILL_SCHEMAS_DIR / schema.name] = schema.read_bytes()
    return rendered


def existing_generated(repo_root: Path) -> set[Path]:
    """Files currently under the generated directories (dotfiles ignored)."""
    found: set[Path] = set()
    for directory in GENERATED_DIRS:
        absolute = repo_root / directory
        if not absolute.is_dir():
            continue
        for path in absolute.rglob("*"):
            relative = path.relative_to(repo_root)
            if path.is_file() and not any(part.startswith(".") for part in relative.parts):
                found.add(relative)
    return found


def stale_files(repo_root: Path = REPO_ROOT, rendered: Rendered | None = None) -> list[str]:
    """One line per generated file that is missing, out of date or unexpected."""
    rendered = rendered or build_outputs(repo_root)
    problems: list[str] = []
    for path, content in sorted(rendered.files.items()):
        absolute = repo_root / path
        if not absolute.is_file():
            problems.append(f"missing: {path}")
        elif absolute.read_bytes() != content:
            problems.append(f"stale: {path}")
    for path in sorted(existing_generated(repo_root) - set(rendered.files)):
        problems.append(f"unexpected: {path}")
    return problems


def write_outputs(repo_root: Path = REPO_ROOT, rendered: Rendered | None = None) -> list[str]:
    """Write every changed file and delete unexpected ones; return what changed."""
    rendered = rendered or build_outputs(repo_root)
    changed: list[str] = []
    for path, content in sorted(rendered.files.items()):
        absolute = repo_root / path
        if absolute.is_file() and absolute.read_bytes() == content:
            continue
        absolute.parent.mkdir(parents=True, exist_ok=True)
        temp = absolute.with_name(f".{absolute.name}.tmp")
        temp.write_bytes(content)
        temp.replace(absolute)
        changed.append(f"wrote: {path}")
    for path in sorted(existing_generated(repo_root) - set(rendered.files)):
        (repo_root / path).unlink()
        changed.append(f"deleted: {path}")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        rendered = build_outputs(args.repo_root)
    except RenderError as exc:
        print(f"render_profiles: {exc}", file=sys.stderr)
        return 2
    for warning in rendered.warnings:
        print(f"warning: {warning}", file=sys.stderr)
    if args.check:
        problems = stale_files(args.repo_root, rendered)
        for line in problems:
            print(line)
        if problems:
            print(
                "Generated files are out of date: run scripts/render_profiles.py", file=sys.stderr
            )
            return 1
        print(f"{len(rendered.files)} generated files are up to date.")
        return 0
    for line in write_outputs(args.repo_root, rendered):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())

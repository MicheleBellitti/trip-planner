"""Database schema (SQLAlchemy 2, async) and session plumbing.

Tables follow the "Tabelle" section of the implementation doc: `plans`, `events`, `fx_rates`,
plus `destination_covers` (the Wikimedia cover photo cache, app/covers.py), `eval_runs`
(the uploaded eval results, app/evals_store.py) and the web app's own Better Auth tables
(`users`, `auth_sessions`, `auth_accounts`, `auth_verifications`; web/lib/auth.ts writes them,
the backend reads `users` and stores `users.id` on plans).
Every change here ships with an Alembic migration in backend/migrations/ (one per PR);
tests/test_db.py fails when the models and the migrations drift apart.
"""

from __future__ import annotations

import datetime as dt
import uuid
from collections.abc import AsyncIterator
from decimal import Decimal
from enum import StrEnum
from typing import TYPE_CHECKING, Annotated, Any, ClassVar

from fastapi import Depends, Request
from sqlalchemy import (
    CHAR,
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    MetaData,
    Numeric,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.ext.asyncio import (
    AsyncEngine,
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

if TYPE_CHECKING:
    from app.config import Settings

# Deterministic constraint names, so autogenerated migrations are stable and reviewable.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

JsonObject = dict[str, Any]


class PlanStatus(StrEnum):
    """Lifecycle of a plan (`plans.status`)."""

    RUNNING = "running"
    READY = "ready"
    FAILED = "failed"
    BUDGET_PAUSED = "budget_paused"
    BLOCKED = "blocked"
    INTERRUPTED = "interrupted"


_STATUS_VALUES = ", ".join(f"'{status.value}'" for status in PlanStatus)


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map: ClassVar[dict[Any, Any]] = {
        # none_as_null: a Python None is stored as SQL NULL, never as the JSON literal 'null'.
        JsonObject: JSONB(none_as_null=True),
        dt.datetime: DateTime(timezone=True),
    }


class UserRecord(Base):
    """An account of the web app's own Better Auth (web/lib/auth.ts; AUTH_MODE=atlas).

    Better Auth's core `user` model, with snake_case columns through its `fields` mapping. The
    web app writes these rows (sign-up, profile), the backend only reads them and stores `id`
    on new plans (`PlanRecord.user_id`). Deleting a user deletes their plans, sessions and
    linked accounts (ON DELETE CASCADE): the "delete my account" path of the data-rights work.
    `name` is Better Auth's required display name; a magic-link sign-up leaves it empty.
    """

    __tablename__ = "users"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str] = mapped_column(Text, default="", server_default=text("''"))
    email: Mapped[str] = mapped_column(Text, unique=True)
    email_verified: Mapped[bool] = mapped_column(
        Boolean, default=False, server_default=text("false")
    )
    image: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class PlanRecord(Base):
    """One planning run: the request, its Managed Agents session, the result and its cost."""

    __tablename__ = "plans"
    __table_args__ = (CheckConstraint(f"status IN ({_STATUS_VALUES})", name="status"),)

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True, default=uuid.uuid4, server_default=func.gen_random_uuid()
    )
    user_email: Mapped[str] = mapped_column(Text)
    # The owner's `users.id` when the user signed in with the web app's own accounts
    # (AUTH_MODE=atlas, `Settings.plans_carry_user_id`); NULL for plans of TripTracker's one user
    # and of AUTH_MODE=local. Ownership is still decided by `user_email` until the switch.
    user_id: Mapped[str | None] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    # Managed Agents session id; NULL until the session has been created.
    session_id: Mapped[str | None] = mapped_column(Text)
    agent_profile: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(
        Text, default=PlanStatus.RUNNING.value, server_default=PlanStatus.RUNNING.value
    )
    # The validated PlanRequest, as submitted to POST /plans.
    request: Mapped[JsonObject]
    # The accepted Plan (submit_plan input) and the TripTracker Trip translated from it.
    plan: Mapped[JsonObject | None]
    trip: Mapped[JsonObject | None]
    # Cumulative Managed Agents list cost, US cents (never euro).
    cost_cents: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    # The session's current budget cap, US cents: set with session_id at start, raised by
    # "Continua". NULL until the session exists. The UI draws cost_cents against it.
    budget_cents: Mapped[int | None] = mapped_column(Integer)
    submit_attempts: Mapped[int] = mapped_column(Integer, default=0, server_default=text("0"))
    # Versions of the coordinator, subagents and skills that produced the plan, plus the git sha.
    agent_versions: Mapped[JsonObject | None]
    # Why the plan ended failed/blocked/interrupted, for the UI and the logs.
    failure_reason: Mapped[str | None] = mapped_column(Text)
    # When the plan last entered `running`: the insert, then every "Continua". The hourly
    # stuck check measures its 45 minutes from here.
    running_since: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    # When the user (or the stuck check) asked to interrupt; survives a restart, so a resumed
    # consumer still turns the coming end_turn into `interrupted`. NULL if never asked.
    interrupt_requested_at: Mapped[dt.datetime | None]
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class EventRecord(Base):
    """A normalized UI event of a plan (UIEvent), in `seq` order; replayed by the SSE stream.

    The primary key (plan_id, seq) is also the index used to read a plan's events in order,
    and deleting a plan deletes its events (ON DELETE CASCADE).
    """

    __tablename__ = "events"

    plan_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("plans.id", ondelete="CASCADE"), primary_key=True
    )
    seq: Mapped[int] = mapped_column(Integer, primary_key=True)
    ts: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    agent: Mapped[str] = mapped_column(Text)
    kind: Mapped[str] = mapped_column(Text)
    title: Mapped[str] = mapped_column(Text)
    detail: Mapped[JsonObject | None]
    # Cumulative session cost when known.
    cost_cents: Mapped[int | None] = mapped_column(Integer)
    # Managed Agents event id: unique, so a resumed consumer never stores an event twice.
    ma_event_id: Mapped[str | None] = mapped_column(Text, unique=True)


class AuthSessionRecord(Base):
    """A Better Auth session of the web app's own accounts (its core `session` model).

    The web app writes and reads these; the backend never does (it asks the web app's
    get-session endpoint, app/auth.py), but Alembic owns the table like every other one, so one
    `alembic upgrade head` prepares a database for both services (`tests/test_db.py` keeps the
    models and the migrations together). `token` is the session token the signed cookie carries.
    """

    __tablename__ = "auth_sessions"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    user_id: Mapped[str] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    token: Mapped[str] = mapped_column(Text, unique=True)
    expires_at: Mapped[dt.datetime]
    ip_address: Mapped[str | None] = mapped_column(Text)
    user_agent: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class AuthAccountRecord(Base):
    """A sign-in method linked to a user (Better Auth's core `account` model): the Google
    account (`provider_id` "google", with its tokens) or the magic-link credential. The backend
    never reads it; the web app owns it."""

    __tablename__ = "auth_accounts"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    user_id: Mapped[str] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    account_id: Mapped[str] = mapped_column(Text)
    provider_id: Mapped[str] = mapped_column(Text)
    access_token: Mapped[str | None] = mapped_column(Text)
    refresh_token: Mapped[str | None] = mapped_column(Text)
    id_token: Mapped[str | None] = mapped_column(Text)
    access_token_expires_at: Mapped[dt.datetime | None]
    refresh_token_expires_at: Mapped[dt.datetime | None]
    scope: Mapped[str | None] = mapped_column(Text)
    password: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class AuthVerificationRecord(Base):
    """A pending verification of Better Auth (its core `verification` model): a magic-link
    token or an OAuth state, keyed by `identifier`, gone after `expires_at`. The web app owns it."""

    __tablename__ = "auth_verifications"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    identifier: Mapped[str] = mapped_column(Text, index=True)
    value: Mapped[str] = mapped_column(Text)
    expires_at: Mapped[dt.datetime]
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class WaitlistRecord(Base):
    """An address that asked for an invitation, or that was invited (the web app's closed beta).

    One row per address (`email` is the key, trimmed and lower-cased by the web app). A row with
    `invited_at` NULL is a request waiting on the landing's or the login's waitlist; once an
    admin invites it (`invited_at`, `invited_by`), the web app's sign-up policy lets that address
    create an account (web/lib/auth.ts, web/lib/server/waitlist.ts), and the invitation email's
    departure is recorded in `invitation_sent_at`. `source` says where the row came from
    ("landing", "login" or "admin"); `note` is what the person wrote, at most a few lines. The
    web app writes and reads the table; the backend only migrates it (Alembic owns every table).
    """

    __tablename__ = "waitlist"

    email: Mapped[str] = mapped_column(Text, primary_key=True)
    note: Mapped[str] = mapped_column(Text, default="", server_default=text("''"))
    source: Mapped[str] = mapped_column(Text)
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    invited_at: Mapped[dt.datetime | None]
    invited_by: Mapped[str | None] = mapped_column(Text)
    invitation_sent_at: Mapped[dt.datetime | None]
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class FxRateRecord(Base):
    """Cached exchange rate: units of `currency` per 1 EUR on `date`, from `source`.

    One rate per currency per day **per source**: the source is part of the key, because a
    Banca d'Italia daily rate and the InforEuro monthly rate (stored under the first day of its
    month) can share a date, and neither may hide the other (see fx.py).
    """

    __tablename__ = "fx_rates"

    date: Mapped[dt.date] = mapped_column(primary_key=True)
    currency: Mapped[str] = mapped_column(CHAR(3), primary_key=True)
    # `bdi_daily` or `inforeuro_monthly` (fx.FxSource).
    source: Mapped[str] = mapped_column(Text, primary_key=True)
    rate: Mapped[Decimal] = mapped_column(Numeric)


class DestinationCoverRecord(Base):
    """Cached cover photo of a destination (app/covers.py), so Wikimedia is asked once per
    destination, not once per page view.

    `destination_key` is the normalized destination name (`covers.cache_key`). `cover` is the
    `covers.Cover` JSON, or NULL when no usable free image exists (a cached miss, retried after
    `covers.MISS_TTL`; a found cover is refreshed after `covers.COVER_TTL`). Transient failures
    are never stored here.
    """

    __tablename__ = "destination_covers"

    destination_key: Mapped[str] = mapped_column(Text, primary_key=True)
    cover: Mapped[JsonObject | None]
    fetched_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())


class EvalRunRecord(Base):
    """One uploaded eval run (the JSON `evals/run.py` writes), for the eval history page.

    `run_key` (profile, git sha and start time, `evals_store.run_key`) makes an upload
    idempotent. The first-class columns are the ones the history is sorted and filtered by;
    `summary` holds the list fields computed at ingest (`evals_store.summarize_run`), so the
    list never reads `results`, the whole document (up to 5 MB). `comparison` is evals/compare.py's
    `--json`, NULL when the run was not compared.
    """

    __tablename__ = "eval_runs"

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True, default=uuid.uuid4, server_default=func.gen_random_uuid()
    )
    run_key: Mapped[str] = mapped_column(Text, unique=True)
    profile: Mapped[str] = mapped_column(Text)
    git_sha: Mapped[str | None] = mapped_column(Text)
    started_at: Mapped[dt.datetime]
    finished_at: Mapped[dt.datetime | None]
    aborted: Mapped[bool] = mapped_column(Boolean, default=False, server_default=text("false"))
    summary: Mapped[JsonObject]
    results: Mapped[JsonObject]
    comparison: Mapped[JsonObject | None]
    workflow_run_url: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[dt.datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[dt.datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


def create_engine(settings: Settings) -> AsyncEngine:
    """An async engine for DATABASE_URL (already normalized to postgresql+asyncpg).

    hide_parameters keeps bound values (e.g. user_email) out of SQLAlchemy error messages,
    which end up in log lines: CLAUDE.md forbids personal data in logs."""
    return create_async_engine(
        settings.database_url.get_secret_value(), pool_pre_ping=True, hide_parameters=True
    )


def create_session_factory(engine: AsyncEngine) -> async_sessionmaker[AsyncSession]:
    return async_sessionmaker(engine, expire_on_commit=False)


async def get_db(request: Request) -> AsyncIterator[AsyncSession]:
    """FastAPI dependency: one session per request. Handlers commit explicitly; anything not
    committed is rolled back when the session closes."""
    session_factory: async_sessionmaker[AsyncSession] = request.app.state.session_factory
    async with session_factory() as session:
        yield session


DbSession = Annotated[AsyncSession, Depends(get_db)]

"""Read the profile's lockfile and resolve its agents, environment and skills.

Spec: "Agenti (Managed Agents)" (definition as code, two profiles chosen with AGENT_PROFILE),
"Eval strutturate e versioning dei prompt" (pinned versions, `plans.agent_versions`) and
"Deploy e configurazione" ("Il backend legge gli ID degli agenti dal lockfile"). Format and
caveats: docs/managed-agents-notes.md §2h.

The lockfile is generated by `ant apply` (or scripts/bootstrap.py, which writes the same
format and the same keys) and never edited by hand. There is one per profile, because a
lockfile is bound to one workspace (notes §2h): `ant apply --lock-file
backend/claude-lock.<profile>.json profiles/<profile>`, run from the repository root. It lives
inside backend/ because Railway deploys the service with root directory `backend/` and ships
only that directory. The backend only reads it, at startup, from `Settings.lockfile_path`
(LOCKFILE_PATH, default `backend/claude-lock.<AGENT_PROFILE>.json`):

    {"version": 1,
     "origin": {"base_url": "...", "organization_id": "...", "workspace_id": "wrkspc_..."},
     "resources": {
       "../profiles/development/agents/coordinator.md":
           {"kind": "agent", "id": "agent_...", "version": "3", "hash": "...", ...},
       "../profiles/development/environments/cloud.yaml":
           {"kind": "environment", "id": "env_...", ...},
       "../skills/booking-links":
           {"kind": "skill", "id": "skill_...", "version": "skver_...", ...}}}

Keys are paths relative to the LOCKFILE's directory, which is what ant writes (anthropic-cli
v1.40.0: pkg/cmd/apply.go keys the loader with `lock.Root()`, core/lock.go defines `Root()` as
`filepath.Dir(lf.Path)`, core/loader.go `keyFor` renders each path relative to it with a `./`
or `../` prefix). The lockfiles sit in backend/ and the profile files and shared skills at the
repository root, so the keys are `../profiles/<profile>/...` and `../skills/<name>`.

Resolution rules for profile P (stable; the agents-as-code work must produce matching keys):

- Keys are normalized lexically (forward slashes, `posixpath.normpath`, a `./` prefix unless
  the key climbs with `../`), never resolved on disk: the image ships without profiles/ and
  skills/. A key is *profiled* when it contains the segments `profiles/<name>/`; it belongs
  to P when `<name> == P`.
- Legacy keys: the first bootstrap.py keyed resources from the repository root
  (`./profiles/<profile>/...`, `./skills/<name>`). They still resolve, exactly like their
  `../` form, and `load_roster` logs the deprecation warning `lockfile_legacy_keys` (apply
  again with ant or bootstrap.py, which rewrites them). A `./profiles/` or `./skills/` key is
  legacy only when the lockfile's directory has no such directory of its own: a lockfile kept
  next to profiles/ (evals/README.md's scratch apply) is keyed `./` by ant itself.
- Two-profile lockfile (any profiled key present): agents and the environment must come from
  P's keys; unprofiled agent/environment keys are ignored. Skills are shared and never profiled.
- Single-profile lockfile (no profiled key, e.g. files applied from a flat `agents/` tree):
  every agent/environment key is used as is. The layout of CLAUDE.md
  (`profiles/<profile>/agents/<name>.md`, one lockfile per profile) gives profiled keys, so
  a lockfile applied for the other profile fails loudly instead of running the wrong roster.
- Agent name = file stem (`coordinator.md` -> `coordinator`). The coordinator and the four
  subagents (flights, lodging, activities, transport) must each match exactly one `kind:
  agent` resource; exactly one `kind: environment` must match. Skill name = last path segment.
- An agent `version` is an integer string ("3"), anything else is a `LockfileError`: it pins
  the session. A skill `version` is informational (the coordinator version pins its skills on
  the server; the backend only records them in `plans.agent_versions`), so its format never
  makes the planner unavailable. bootstrap.py records a version id of the GA skills API
  (`skver_...`); ant uses the Beta skills API and may record an epoch-like digit string
  (`1759178010641129`). Both are kept as they are, and so is any other short token. A
  version that is missing, not a string, or not a plain token becomes None, and `load_roster`
  logs `lockfile_skill_version_unrecognized` for it and for unknown tokens.

Sessions are always created with the coordinator pinned to the lockfile version, in both
profiles. The subagents and skills are pinned inside the coordinator version by `ant apply`
(notes I13); the backend records their lockfile versions in `plans.agent_versions` only.
"""

from __future__ import annotations

import hashlib
import json
import posixpath
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from types import MappingProxyType
from typing import TYPE_CHECKING, Any, Literal, cast
from urllib.parse import urlsplit

import structlog
from pydantic import BaseModel, ConfigDict, ValidationError

from app.events import AgentName
from app.ma_client import AgentPin

if TYPE_CHECKING:
    from app.config import AgentProfile, Settings

LOCKFILE_VERSION = 1
PROFILES_DIR = "profiles"
SKILLS_DIR = "skills"
KEY_PREFIX = "../"
"""How the keys of backend/claude-lock.<profile>.json start: relative to backend/, the
lockfile's directory, the profile files and skills sit one level up."""
LEGACY_KEY_DIRS = frozenset({PROFILES_DIR, SKILLS_DIR})
"""`./<dir>/...` keys of these directories are the old repository-root form (module docstring)."""

COORDINATOR: AgentName = AgentName.COORDINATOR
REQUIRED_AGENTS: tuple[AgentName, ...] = tuple(AgentName)
"""coordinator, flights, lodging, activities, transport: all five must resolve."""

ResourceKind = Literal["agent", "environment", "skill", "memory_store", "deployment", "vault"]

SKILL_VERSION_PREFIX = "skver_"
"""A skill version id of the GA skills API (`client.skills`, what bootstrap.py records)."""
MAX_SKILL_VERSION_LENGTH = 128
SkillVersionKind = Literal["version_id", "epoch", "other", "invalid"]
"""`version_id`: `skver_...` (GA API, bootstrap.py); `epoch`: a digit string (Beta API, ant);
`other`: another plain token, kept; `invalid`: missing or not a plain token, recorded as None."""

_AGENT_VERSION = re.compile(r"[1-9][0-9]*")
_SKILL_VERSION_ID = re.compile(rf"{SKILL_VERSION_PREFIX}[A-Za-z0-9_-]+")
_SKILL_EPOCH_VERSION = re.compile(r"[0-9]{1,32}")
_SKILL_VERSION_TOKEN = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.:+-]*")
_URL_KEY = re.compile(r"^[a-z][a-z0-9+.-]*://", re.IGNORECASE)

log = structlog.get_logger(__name__)


class LockfileError(Exception):
    """The lockfile is missing, unreadable, of an unknown version, or doesn't resolve the active
    profile unambiguously. The message names the file and the offending key(s), never IDs of
    other workspaces' resources. At startup this makes the planner "unavailable" (POST /plans
    answers 503), it never crashes /health."""


class LockOrigin(BaseModel):
    """Where the resources live: the API base URL, organization and workspace."""

    model_config = ConfigDict(extra="allow", frozen=True)

    base_url: str | None = None
    organization_id: str | None = None
    workspace_id: str | None = None


class LockedResource(BaseModel):
    """One entry of `resources`: what `ant apply` created for one file or directory."""

    model_config = ConfigDict(extra="allow", frozen=True)

    kind: str
    id: str
    version: str | None = None
    hash: str | None = None
    remote_hash: str | None = None


class Lockfile(BaseModel):
    """The whole `claude-lock.json`. Unknown top-level keys are kept (ant may add some)."""

    model_config = ConfigDict(extra="allow", frozen=True)

    version: int
    origin: LockOrigin
    resources: dict[str, LockedResource]


@dataclass(frozen=True, slots=True)
class SkillPin:
    """A custom skill and the version the lockfile recorded (None when it recorded none that
    looks like a version: module docstring)."""

    name: str
    id: str
    version: str | None


@dataclass(frozen=True, slots=True)
class Roster:
    """The resolved agents, environment and skills of one profile."""

    profile: AgentProfile
    coordinator: AgentPin
    subagents: Mapping[AgentName, AgentPin]
    """flights, lodging, activities, transport -> pin (never the coordinator)."""
    environment_id: str
    skills: Mapping[str, SkillPin]
    lockfile_path: Path
    lockfile_sha256: str
    """sha256 of the lockfile bytes, recorded with every plan."""
    workspace_id: str | None

    def agent_versions(
        self, *, git_sha: str | None, trip_schema_sha256: str | None
    ) -> dict[str, Any]:
        """The JSON stored in `plans.agent_versions` when a plan starts:

            {"profile": "development",
             "coordinator": {"id": "agent_...", "version": 3},
             "subagents": {"flights": {"id": ..., "version": ...}, ...},
             "skills": {"booking-links": {"id": "skill_...", "version": "skver_..."}, ...},
             # a skill version may also be an epoch string (ant) or null (unrecognized)
             "environment_id": "env_...",
             "lockfile_sha256": "...", "trip_schema_sha256": "...", "git_sha": "..."}

        Keys are stable: evals/run.py and evals/compare.py read them.
        """
        return {
            "profile": self.profile,
            "coordinator": _pin_json(self.coordinator),
            "subagents": {
                name.value: _pin_json(self.subagents[name])
                for name in REQUIRED_AGENTS
                if name in self.subagents
            },
            "skills": {
                name: {"id": self.skills[name].id, "version": self.skills[name].version}
                for name in sorted(self.skills)
            },
            "environment_id": self.environment_id,
            "lockfile_sha256": self.lockfile_sha256,
            "trip_schema_sha256": trip_schema_sha256,
            "git_sha": git_sha,
        }


def _pin_json(pin: AgentPin) -> dict[str, Any]:
    return {"id": pin.id, "version": pin.version}


def normalize_key(key: str) -> str:
    """`agents\\coordinator.md` / `agents/coordinator.md` -> `./agents/coordinator.md`;
    `../profiles/x/../development/agents/c.md` -> `../profiles/development/agents/c.md`. A key
    is a path relative to the lockfile's directory, normalized without touching the disk."""
    text = key.strip()
    if _URL_KEY.match(text):
        return text  # a skill referenced by URL: kept as written
    text = text.replace("\\", "/")
    if text.startswith("/"):
        return posixpath.normpath(text)
    normalized = posixpath.normpath(text)
    if normalized == ".." or normalized.startswith("../"):
        return normalized
    return f"./{normalized}"


def key_profile(key: str) -> str | None:
    """The profile a normalized key belongs to (`./profiles/production/agents/x.md` ->
    `production`), or None for an unprofiled key."""
    if _URL_KEY.match(key):
        return None
    segments = normalize_key(key).split("/")
    # `profiles/<name>/` must be followed by at least one more segment.
    for index, segment in enumerate(segments[:-2]):
        if segment == PROFILES_DIR and segments[index + 1] not in {"", ".", ".."}:
            return segments[index + 1]
    return None


def legacy_keys(keys: Iterable[str], lockfile_dir: Path) -> list[str]:
    """The keys (normalized, sorted) written in the old repository-root form: `./profiles/...`
    or `./skills/...` in a lockfile whose own directory has no `profiles/` or `skills/`
    (module docstring). They resolve like their `../` form; `load_roster` warns about them."""
    found: set[str] = set()
    for key in keys:
        if _URL_KEY.match(key.strip()):
            continue
        segments = normalize_key(key).split("/")
        if len(segments) < 3 or segments[0] != "." or segments[1] not in LEGACY_KEY_DIRS:
            continue
        try:
            beside_the_lockfile = (lockfile_dir / segments[1]).is_dir()
        except OSError:
            beside_the_lockfile = False
        if not beside_the_lockfile:
            found.add("/".join(segments))
    return sorted(found)


def skill_version_kind(version: object) -> SkillVersionKind:
    """Classify a skill's lockfile `version` (module docstring). Never raises."""
    if not isinstance(version, str) or not 0 < len(version) <= MAX_SKILL_VERSION_LENGTH:
        return "invalid"
    if _SKILL_VERSION_ID.fullmatch(version):
        return "version_id"
    if _SKILL_EPOCH_VERSION.fullmatch(version):
        return "epoch"
    if _SKILL_VERSION_TOKEN.fullmatch(version):
        return "other"
    return "invalid"


def read_lockfile(path: Path) -> Lockfile:
    """Parse `path`. Raises `LockfileError` when it is missing, not JSON, not the expected
    shape, or `version != LOCKFILE_VERSION`."""
    return _parse_lockfile(_read_bytes(path), path)


def _read_bytes(path: Path) -> bytes:
    try:
        return path.read_bytes()
    except FileNotFoundError as exc:
        msg = f"lockfile {path} does not exist (run `ant apply --lock-file ...` first)"
        raise LockfileError(msg) from exc
    except OSError as exc:
        msg = f"lockfile {path} cannot be read: {exc.strerror or type(exc).__name__}"
        raise LockfileError(msg) from exc


def _parse_lockfile(content: bytes, path: Path) -> Lockfile:
    try:
        data: Any = json.loads(content)
    except ValueError as exc:
        msg = f"lockfile {path} is not valid JSON: {exc}"
        raise LockfileError(msg) from exc
    if not isinstance(data, dict):
        msg = f"lockfile {path} is not a JSON object"
        raise LockfileError(msg)
    document = cast(dict[str, Any], data)
    version = document.get("version")
    if isinstance(version, bool) or version != LOCKFILE_VERSION:
        msg = (
            f"lockfile {path} has version {version!r}; this backend reads version "
            f"{LOCKFILE_VERSION}"
        )
        raise LockfileError(msg)
    if document.get("origin") is None:
        document["origin"] = {}  # ant omits an empty origin
    resources = document.get("resources")
    if not isinstance(resources, dict):
        msg = f"lockfile {path} has no `resources` object"
        raise LockfileError(msg)
    for entry in cast(dict[str, Any], resources).values():
        if isinstance(entry, dict):
            entry_map = cast(dict[str, Any], entry)
            raw_version = entry_map.get("version")
            if isinstance(raw_version, int) and not isinstance(raw_version, bool):
                entry_map["version"] = str(raw_version)  # ant writes strings; accept ints
            elif entry_map.get("kind") == "skill" and not isinstance(raw_version, str | None):
                # A skill version never blocks (module docstring): an odd one is dropped here
                # and reported by load_roster, instead of failing the whole lockfile.
                entry_map["version"] = None
    try:
        return Lockfile.model_validate(document)
    except ValidationError as exc:
        problems = "; ".join(
            f"{'.'.join(str(part) for part in error['loc'])}: {error['msg']}"
            for error in exc.errors()[:10]
        )
        msg = f"lockfile {path} does not have the expected shape: {problems}"
        raise LockfileError(msg) from exc


def resolve_roster(lockfile: Lockfile, profile: AgentProfile, *, path: Path, sha256: str) -> Roster:
    """Apply the module's resolution rules for `profile`. Pure. Raises `LockfileError` listing
    every missing or ambiguous agent/environment at once."""
    entries = [(normalize_key(key), resource) for key, resource in lockfile.resources.items()]
    key_profiles = {key: key_profile(key) for key, _ in entries}
    two_profiles = any(found is not None for found in key_profiles.values())

    def belongs(key: str) -> bool:
        found = key_profiles[key]
        return found == profile if two_profiles else found is None

    agents: dict[str, list[tuple[str, LockedResource]]] = {}
    environments: list[tuple[str, LockedResource]] = []
    skills: dict[str, list[tuple[str, LockedResource]]] = {}
    for key, resource in entries:
        if resource.kind == "skill":
            # Shared by both profiles; a skill under another profile's tree is not ours.
            if key_profiles[key] in {None, profile}:
                skills.setdefault(_skill_name(key), []).append((key, resource))
        elif resource.kind == "agent" and belongs(key):
            agents.setdefault(PurePosixPath(key).stem, []).append((key, resource))
        elif resource.kind == "environment" and belongs(key):
            environments.append((key, resource))

    problems: list[str] = []
    if two_profiles and not any(found == profile for found in key_profiles.values()):
        others = sorted({found for found in key_profiles.values() if found is not None})
        problems.append(
            f"no resource belongs to profile {profile!r} (the lockfile holds "
            f"{', '.join(repr(other) for other in others)}): it was applied for another profile"
        )

    pins: dict[AgentName, AgentPin] = {}
    for name in REQUIRED_AGENTS:
        matches = agents.get(name.value, [])
        if not matches:
            expected = f"{KEY_PREFIX}{PROFILES_DIR}/{profile}/agents/{name.value}.md"
            problems.append(
                f"agent {name.value!r}: no `kind: agent` entry (expected {expected}, relative "
                "to the lockfile's directory)"
            )
            continue
        if len(matches) > 1:
            keys = ", ".join(sorted(key for key, _ in matches))
            problems.append(f"agent {name.value!r}: {len(matches)} entries match ({keys})")
            continue
        key, resource = matches[0]
        version = resource.version or ""
        if not _AGENT_VERSION.fullmatch(version):
            problems.append(
                f"agent {name.value!r} ({key}): version {resource.version!r} is not a positive "
                "integer string"
            )
            continue
        pins[name] = AgentPin(id=resource.id, version=int(version))

    environment_id: str | None = None
    if not environments:
        problems.append(
            f"environment: no `kind: environment` entry (expected "
            f"{KEY_PREFIX}{PROFILES_DIR}/{profile}/environments/<name>.yaml)"
        )
    elif len(environments) > 1:
        keys = ", ".join(sorted(key for key, _ in environments))
        problems.append(f"environment: {len(environments)} entries match ({keys})")
    else:
        environment_id = environments[0][1].id

    skill_pins: dict[str, SkillPin] = {}
    for name, matches in sorted(skills.items()):
        if len(matches) > 1:
            keys = ", ".join(sorted(key for key, _ in matches))
            problems.append(f"skill {name!r}: {len(matches)} entries match ({keys})")
            continue
        _, resource = matches[0]
        version = resource.version if skill_version_kind(resource.version) != "invalid" else None
        skill_pins[name] = SkillPin(name=name, id=resource.id, version=version)

    if problems or environment_id is None:
        details = "\n  - ".join(problems)
        msg = f"lockfile {path} does not resolve profile {profile!r}:\n  - {details}"
        raise LockfileError(msg)

    return Roster(
        profile=profile,
        coordinator=pins[COORDINATOR],
        subagents=MappingProxyType(
            {name: pin for name, pin in pins.items() if name is not COORDINATOR}
        ),
        environment_id=environment_id,
        skills=MappingProxyType(skill_pins),
        lockfile_path=path,
        lockfile_sha256=sha256,
        workspace_id=lockfile.origin.workspace_id,
    )


def _skill_name(key: str) -> str:
    if _URL_KEY.match(key):
        url_path = urlsplit(key).path.rstrip("/")
        return url_path.rsplit("/", 1)[-1] or key
    return PurePosixPath(key.rstrip("/")).name


def load_roster(settings: Settings) -> Roster:
    """`read_lockfile(settings.lockfile_path)` + `resolve_roster(..., settings.agent_profile)`.
    Called once by `sessions.start_planner()`; the result is immutable for the process life (a
    new `ant apply` reaches the backend through a deploy, as the spec says).

    Logs, without failing: `lockfile_legacy_keys` (deprecated repository-root keys) and
    `lockfile_skill_version_unrecognized` (skill versions kept as unknown tokens or dropped).
    Neither names a resource id."""
    path = settings.lockfile_path
    content = _read_bytes(path)
    lockfile = _parse_lockfile(content, path)
    sha256 = hashlib.sha256(content).hexdigest()
    roster = resolve_roster(lockfile, settings.agent_profile, path=path, sha256=sha256)
    legacy = legacy_keys(lockfile.resources, path.parent)
    if legacy:
        log.warning(
            "lockfile_legacy_keys",
            lockfile=str(path),
            count=len(legacy),
            example=legacy[0],
            expected=KEY_PREFIX + legacy[0].removeprefix("./"),
            fix="keys are relative to the lockfile's directory: apply again with ant or "
            "scripts/bootstrap.py to rewrite them",
        )
    unrecognized = {
        name: skill_version_kind(pin.version)
        for name, pin in sorted(roster.skills.items())
        if skill_version_kind(pin.version) in ("other", "invalid")
    }
    if unrecognized:
        log.warning("lockfile_skill_version_unrecognized", lockfile=str(path), skills=unrecognized)
    return roster
